/* ---------- section-local helpers (prefix r04, nothing global changed) ----------
   xfig(src, [W,H], marks, layers): like rfig, plus free overlay layers drawn in the
   image's own pixel coordinates. A layer is {r:[x,y,w,h] (normalized), k, step, svg}:
   k = 'cov' fades away on its step (a white card carrying its own drawing),
   k = 'b' (default) fades in on its step, k = 'fix' is always on (not a build).
   svg = inner SVG markup in image pixels. */

const xfig = (src, [W, H], marks=[], layers=[]) => {
  const base = rfig(src, W/H, marks);
  const lay = layers.map(L => {
    const [x,y,w,h] = L.r, k = L.k === 'cov' ? 'cov r04-card b' : L.k === 'fix' ? 'r04-lay r04-fix' : 'r04-lay b';
    return `<div class="${k}" ${L.step!=null?`data-step="${L.step}"`:''}
      style="left:${x*100}%;top:${y*100}%;width:${w*100}%;height:${h*100}%">
      <svg viewBox="${x*W} ${y*H} ${w*W} ${h*H}" preserveAspectRatio="none">${L.svg||''}</svg></div>`;
  }).join('');
  return base.replace(/<\/div>\s*<\/div>\s*<\/figure>\s*$/, `${lay}</div></div></figure>`);
};

